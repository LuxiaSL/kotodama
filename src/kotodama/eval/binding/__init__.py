"""The binding suite: every binding battery, one scorer.

Every battery here measures the same thing: the closed-candidate, first-token logprob at the last prompt position. So
there is one scorer (``kotodama.eval.riders.score.score_logprob_items``, the implementation shared by the training
loop and ``/logprobs``), one model loader (kotodama checkpoint or Hugging Face model, :mod:`.models`), one runner
(``python -m kotodama.eval.binding run``) that loads a model once and scores every requested battery, and one
scorecard (``report``). Each battery keeps its own reader, because the batteries compute different statistics.

Batteries (:mod:`.batteries`):
  prompt-row batteries — a frozen jsonl of ``{id, prompt, candidates, gold, …controls}``, scored to rows with
      ``cand_lps`` (stripped candidate → first-token logprob), ``rank_full`` and ``multi_token``:
      ``joinlite-v1`` / ``swapdyn-v1`` (stage gauges), ``stage5-decomp-v1`` / ``stage5-decomp-core`` (the stage-5
      decomposition), and ``capacity-v1`` (binding capacity, generated by :mod:`.capacity`).
  bindprobes batteries — :mod:`kotodama.eval.bindprobes` items rendered per condition with ``build_prompt`` and scored
      to bindprobes grid rows (``score_row``), so ``bindprobes aggregate`` reads them unchanged.
"""
