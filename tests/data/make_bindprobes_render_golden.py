"""Write the render golden for the pinned bindprobes batteries (``bindprobes_render_golden.json.gz``).

A bindprobes item file stores each item's ``spec``; the prompt strings are rendered from it at scoring time, so
a file's sha256 pin alone says nothing about the strings a run scores. The golden records them: for every pinned
file (``kotodama.eval.binding.batteries``, kind ``bindprobes``), every item and every condition, the sha256 of
the prompt rendered by the code that generated the file. ``tests/test_bindprobes_render_golden.py`` renders
the same items with the code in this tree and asserts the strings are byte-identical.

The script imports only what every bindprobes version has (``items.load_items``, ``items.build_prompt``,
``items.CONDITIONS``), so it runs against an older checkout of this repository::

    git archive <commit> src | tar -x -C /tmp/old
    python -I tests/data/make_bindprobes_render_golden.py --code-root /tmp/old/src --prompts-dir DIR \\
        --rendered-by <commit> --battery bp-profile=bindprobes-items/items.jsonl:<sha256> ... \\
        --out tests/data/bindprobes_render_golden.json.gz \\
        --sample-out tests/data/bindprobes_render_sample.jsonl.gz [--merge]

``--extra`` takes the same NAME=FILE:SHA256 for a scored item file that no registry battery pins (kept with
``registered: false``, so its generation's templates are covered too). ``--merge`` adds batteries to an existing
golden and sample (a file generated by a later commit is rendered by
that commit's tree). Per battery the golden keeps the file pin, the item count, and per condition the sha256
over every prompt's sha256 in file order (``all``, exact) plus each prompt's first ``DIGEST_HEX`` hex digits
(``items``, concatenated in file order; it names the item that changed). ``render_sha256`` is the sha256 over
the conditions' ``all`` digests in ``CONDITIONS`` order: the value a battery's ``render_sha256`` pin holds.
The sample keeps the first ``PER_STRATUM`` items of every (family, id tag, cell, variant) stratum of each file with its index,
so the CPU suite re-renders every generation's templates without the item files.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

DIGEST_HEX = 8
PER_STRATUM = 1


def file_sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def render_record(path: Path) -> dict[str, Any]:
    """The golden record of one item file, rendered by whichever ``kotodama`` is importable."""
    from kotodama.eval.bindprobes.items import CONDITIONS, build_prompt, load_items

    items = load_items(path)
    conds: dict[str, Any] = {}
    for c in CONDITIONS:
        whole = hashlib.sha256()
        per: list[str] = []
        for it in items:
            d = hashlib.sha256(build_prompt(it, c).encode("utf-8"))
            whole.update(d.digest())
            per.append(d.hexdigest()[:DIGEST_HEX])
        conds[c] = {"all": whole.hexdigest(), "items": "".join(per)}
    render = hashlib.sha256(b"".join(bytes.fromhex(conds[c]["all"]) for c in CONDITIONS)).hexdigest()
    return {"n_items": len(items), "conditions": conds, "render_sha256": render}


def sample_rows(name: str, path: Path) -> list[dict[str, Any]]:
    """The first ``PER_STRATUM`` items of every (family, id tag, cell, variant) stratum, with their index."""
    seen: dict[str, int] = {}
    out: list[dict[str, Any]] = []
    with path.open() as fh:
        for i, line in enumerate(fh):
            row = json.loads(line)
            key = json.dumps([row["family"], row["item_id"].split("_")[0], row["cell"],
                              row["meta"].get("variant")])
            seen[key] = seen.get(key, 0) + 1
            if seen[key] <= PER_STRATUM:
                out.append({"battery": name, "index": i, "item": row})
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--code-root", required=True, help="the src/ directory whose kotodama renders the items")
    ap.add_argument("--prompts-dir", required=True)
    ap.add_argument("--battery", action="append", default=[], help="NAME=RELATIVE_FILE:SHA256 (repeatable)")
    ap.add_argument("--extra", action="append", default=[], help="as --battery, for a file no registry battery pins")
    ap.add_argument("--rendered-by", required=True, help="a label for the tree that rendered (recorded verbatim)")
    ap.add_argument("--out", required=True)
    ap.add_argument("--sample-out", required=True)
    ap.add_argument("--merge", action="store_true", help="add to an existing golden instead of replacing it")
    a = ap.parse_args(argv)
    sys.path.insert(0, str(Path(a.code_root).resolve()))
    out, sample_out = Path(a.out), Path(a.sample_out)
    golden: dict[str, Any] = {"digest_hex": DIGEST_HEX, "batteries": {}}
    sample: list[dict[str, Any]] = []
    if a.merge and out.exists():
        golden = json.loads(gzip.decompress(out.read_bytes()))
    if a.merge and sample_out.exists():
        sample = [json.loads(ln) for ln in gzip.decompress(sample_out.read_bytes()).decode().splitlines()]
    for spec, registered in [(s, True) for s in a.battery] + [(s, False) for s in a.extra]:
        name, rest = spec.split("=", 1)
        rel, pin = rest.rsplit(":", 1)
        path = Path(a.prompts_dir) / rel
        got = file_sha256(path)
        if got != pin:
            raise SystemExit(f"{name}: {path} sha256 {got} != pin {pin}")
        rec = render_record(path)
        golden["batteries"][name] = {"file": rel, "sha256": pin, "rendered_by": a.rendered_by,
                                     "registered": registered, **rec}
        rows = sample_rows(name, path)
        sample = [r for r in sample if r["battery"] != name] + rows
        print(f"{name}: {rec['n_items']} items rendered by {a.rendered_by}; {len(rows)} sampled", flush=True)
    out.write_bytes(gzip.compress(json.dumps(golden, sort_keys=True).encode("utf-8"), mtime=0))
    text = "".join(json.dumps(r, sort_keys=True) + "\n" for r in sample)
    sample_out.write_bytes(gzip.compress(text.encode("utf-8"), mtime=0))
    return 0


if __name__ == "__main__":
    sys.exit(main())
